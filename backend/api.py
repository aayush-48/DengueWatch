@app.get("/cities")
def cities():
    out = []
    for c, meta in CITIES.items():
        df = inf.data(c)
        t0 = df[df.split == "test"].week_start_date.min()
        out.append({"id": c, "name": meta["name"], "start": df.week_start_date.min(),
                    "end": df.week_start_date.max(), "test_start": t0, "weeks": len(df)})
    return clean(out)


@app.get("/data/{city}")
def get_data(city: str, start: str | None = None, end: str | None = None):
    check_city(city)
    df = inf.data(city)
    if start:
        df = df[df.week_start_date >= pd.Timestamp(start)]
    if end:
        df = df[df.week_start_date <= pd.Timestamp(end)]
    cols = ["week_start_date", "season", "season_week", "total_cases", "denv1_cases", "denv2_cases",
            "denv3_cases", "denv4_cases", "incidence_100k", "split"] + CLIMATE_COLS
    return clean(df[cols])


