@app.get("/forecast/{city}")
def forecast(city: str, origin: str | None = None, model: str | None = None,
             hosp_rate: float = Query(0.10, ge=0, le=1), history_weeks: int = 52,
             sensitivity: str = Query("early", pattern="^(early|standard)$")):
    """Forecast for the 8 weeks after `origin` (default: last observed week), the alert
    assessment, and - when the target weeks are in the past - what actually happened."""
    check_city(city)
    met = read_json("metrics.json")[city]
    model = model or met["best_model_by_mean_MAE"]
    if model not in MODEL_ORDER:
        raise HTTPException(400, f"Unknown model. Choose from {MODEL_ORDER}")
    o = inf.origin_index(city, origin)
    g = inf.lookup(city, o, model).sort_values("h")
    meta = inf.target_meta(city, o)
    ch = inf.channel_for(city, meta.season_week)
    f = pd.DataFrame({"target_date": meta.target_date, "h": meta.h, "cases": g.cases.values,
                      "lo": g.cases_lo.values, "hi": g.cases_hi.values,
                      "typical": ch.typical, "warning": ch.warning, "epidemic": ch.epidemic,
                      "actual": g.actual.values})
    df = inf.data(city)
    hist = df.iloc[max(0, o - history_weeks + 1): o + 1]
    hist_ch = inf.channel_for(city, hist.season_week)
    # residual-based anomaly: was the latest week far above what the model expected a week ago?
    prev = inf.lookup(city, o - 1, model)
    prev1 = prev[prev.h == 1]
    surge = None
    if len(prev1) and not np.isnan(prev1.cases_hi.iloc[0]):
        obs = float(df.total_cases.iloc[o])
        surge = {"observed": obs, "expected": float(prev1.cases.iloc[0]),
                 "upper80": float(prev1.cases_hi.iloc[0]),
                 "is_surge": bool(obs > prev1.cases_hi.iloc[0])}
    return clean({
        "city": CITIES[city]["name"], "model": model, "origin_date": df.week_start_date.iloc[o],
        "origin_index": o, "in_sample": bool(df.split.iloc[o] == "train"),
        "beyond_data": bool(o + MAX_HORIZON >= len(df)),
        "forecast": f, "assessment": assess(f, hosp_rate, use_upper=(sensitivity == "early")),
        "sensitivity": sensitivity,
        "history": pd.DataFrame({"week_start_date": hist.week_start_date.values,
                                 "cases": hist.total_cases.values,
                                 "typical": hist_ch.typical, "warning": hist_ch.warning,
                                 "epidemic": hist_ch.epidemic}),
        "latest_week_check": surge,
    })


@app.get("/compare/{city}")
def compare(city: str, origin: str | None = None):
    """All models' forecasts from one origin, side by side."""
    check_city(city)
    o = inf.origin_index(city, origin)
    g = inf.lookup(city, o)
    return clean({"origin_date": inf.data(city).week_start_date.iloc[o],
                  "rows": g[["model", "h", "target_date", "cases", "cases_lo", "cases_hi", "actual"]]})


class WhatIf(BaseModel):
    origin: str | None = None
    temp_delta: float = 0.0
    humidity_pct: float = 0.0
    rain_pct: float = 0.0
    weeks: int = 8


@app.post("/whatif/{city}")
def whatif(city: str, body: WhatIf):
    check_city(city)
    o = inf.origin_index(city, body.origin)
    r = inf.whatif(city, o, body.temp_delta, body.humidity_pct, body.rain_pct, body.weeks)
    meta = inf.target_meta(city, o)
    ch = inf.channel_for(city, meta.season_week)
    return clean({"origin_date": inf.data(city).week_start_date.iloc[o], "table": r["table"],
                  "used_climate": r["used_climate"],
                  "thresholds": pd.DataFrame({"target_date": meta.target_date,
                                              "epidemic": ch.epidemic, "warning": ch.warning})})


@app.post("/upload")
async def upload(file: UploadFile = File(...), hosp_rate: float = 0.10):
    """Forecast a user-supplied weekly case CSV (date + cases columns, >= 3 years)."""
    raw = await file.read()
    try:
        r = inf.upload_forecast(raw, hosp_rate=hosp_rate)
    except inf.UploadError as e:
        raise HTTPException(400, str(e))
    return clean(r)
