# ----------------------------------------------------------------------------- helpers
def clean(obj):
    """Make numpy / pandas values JSON-safe (NaN -> None, timestamps -> ISO dates)."""
    if isinstance(obj, dict):
        return {str(k): clean(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [clean(v) for v in obj]
    if isinstance(obj, pd.DataFrame):
        return clean(obj.to_dict("records"))
    if isinstance(obj, pd.Series):
        return clean(obj.to_dict())
    if isinstance(obj, (pd.Timestamp, np.datetime64)):
        return str(pd.Timestamp(obj).date())
    if isinstance(obj, (np.integer,)):
        return int(obj)
    if isinstance(obj, (np.floating, float)):
        return None if math.isnan(obj) or math.isinf(obj) else float(obj)
    if isinstance(obj, np.bool_):
        return bool(obj)
    return obj


def check_city(city: str):
    if city not in CITIES:
        raise HTTPException(404, f"Unknown city '{city}'. Use one of {list(CITIES)}")


def read_json(name):
    with open(RESULTS / name) as f:
        return json.load(f)


