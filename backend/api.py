@app.get("/eda/{city}")
def get_eda(city: str):
    check_city(city)
    df = eda.load(city)
    dec = eda.stl_decompose(df)
    an = eda.stl_anomalies(dec)
    ccf = eda.cross_correlation(df)
    tr = np.log1p(df[df.split == "train"].total_cases)
    from statsmodels.tsa.stattools import acf, pacf
    summ = read_json("eda_summary.json")[city]
    return clean({
        "summary": summ,
        "stl": dec, "anomalies": an[["week_start_date", "resid", "robust_z"]],
        "seasonal_profile": eda.seasonal_profile(df),
        "ccf": ccf, "serotypes": eda.serotype_share(df).reset_index(),
        "acf": acf(tr, nlags=110).tolist(), "pacf": pacf(tr, nlags=60, method="ywm").tolist(),
        "n_train": int(len(tr)),
        "rolling": pd.DataFrame({"week_start_date": df.week_start_date,
                                 "mean52": df.total_cases.rolling(52, center=True).mean(),
                                 "std52": df.total_cases.rolling(52, center=True).std()}),
    })


